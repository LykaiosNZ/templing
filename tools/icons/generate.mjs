// Reads icons.txt and writes Mdi.g.cs: one MudBlazor-compatible icon string ("<path d=\"...\"/>") per icon.
import { readFileSync, writeFileSync } from 'node:fs';
import * as mdi from '@mdi/js';

const pkg = JSON.parse(readFileSync(new URL('./node_modules/@mdi/js/package.json', import.meta.url)));
const names = readFileSync(new URL('./icons.txt', import.meta.url), 'utf8')
    .split(/\r?\n/).map(l => l.trim()).filter(l => l && !l.startsWith('#'));

const pascal = n => n.split('-').map(p => p[0].toUpperCase() + p.slice(1)).join('');
const lines = names.map(n => {
    const key = 'mdi' + pascal(n);
    const path = mdi[key];
    if (!path) throw new Error(`Unknown icon "${n}" (looked for ${key})`);
    return `    /// <summary>mdi-${n}</summary>\n    public const string ${pascal(n)} = "<path d=\\"${path}\\"/>";`;
});

const out = `// <auto-generated>
// Generated by tools/icons/generate.mjs from @mdi/js ${pkg.version}. Do not edit; add names to tools/icons/icons.txt instead.
// Icons: Pictogrammers Material Design Icons (https://pictogrammers.com), Apache License 2.0.
// </auto-generated>
namespace Templing.Components;

/// <summary>Pictogrammers Material Design Icons, as MudBlazor icon strings (use anywhere an Icon parameter is taken).</summary>
public static class Mdi
{
${lines.join('\n\n')}
}
`;
writeFileSync(new URL('../../src/Templing/Components/Mdi.g.cs', import.meta.url), out);
console.log(`Wrote ${names.length} icon(s) to src/Templing/Components/Mdi.g.cs`);
